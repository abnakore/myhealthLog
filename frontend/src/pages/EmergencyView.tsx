/**
 * Public emergency view — what a first responder gets when they scan the QR code.
 * Backed by GET /api/v1/emergency/card/<token>/.
 *
 * No account required. The token comes from the URL, is validated by the backend,
 * and PIN protection is checked server-side. The page renders the same shared
 * health-summary layout as /app/summary, limited to the sections the owner enabled.
 */
import { useEffect, useState, type FormEvent } from "react";
import { useParams } from "react-router-dom";
import {
  fetchPublicCard,
  verifyEmergencyPin,
  isPinRequired,
  type StaticEmergencyCard,
} from "@/services/emergency";
import { apiErrorMessage } from "@/services/api";
import { formatDate, formatDateTime } from "@/lib/format";
import { LockIcon, ShieldIcon } from "@/components/icons";
import { SEX_LABELS } from "@/types/health";
import { Spinner } from "@/components/ui/Spinner";
import {
  HealthSummary,
  type MedicalSummaryData,
  type SummaryReading,
} from "@/components/summary/HealthSummary";

function tokenSuffix(token: string): string {
  return token.slice(-4).toUpperCase();
}

function InvalidCode({ message }: { message?: string }) {
  useEffect(() => {
    document.title = "Emergency view: code not valid";
  }, []);
  return (
    <main className="mhl-emerg-page grid min-h-dvh place-items-center bg-mhl-emerg px-6 text-mhl-emerg-ink">
      <div className="max-w-sm text-center">
        <span className="mx-auto grid h-14 w-14 place-items-center rounded-full border border-mhl-emerg-ink/25 text-mhl-emerg-amber">
          <ShieldIcon size={26} />
        </span>
        <h1 className="mt-4 text-mhl-title font-bold text-mhl-emerg-ink">This emergency code isn't valid</h1>
        <p className="mt-2 text-mhl-body text-mhl-emerg-muted">
          {message ?? "It may have been regenerated by the owner, or the link may be incomplete."}
        </p>
      </div>
    </main>
  );
}

function PinGate({ code, onUnlock }: { code: string; onUnlock: (card: StaticEmergencyCard) => void }) {
  const [value, setValue] = useState("");
  const [error, setError] = useState<string | null>(null);
  const [busy, setBusy] = useState(false);

  useEffect(() => {
    document.title = "Emergency view: enter PIN";
  }, []);

  async function submit(event: FormEvent) {
    event.preventDefault();
    if (!value.trim()) {
      setError("Enter the PIN.");
      return;
    }
    setBusy(true);
    setError(null);
    try {
      const card = await verifyEmergencyPin(code, value.trim());
      onUnlock(card);
    } catch (err) {
      setError(apiErrorMessage(err));
      setValue("");
    } finally {
      setBusy(false);
    }
  }

  return (
    <main className="mhl-emerg-page grid min-h-dvh place-items-center bg-mhl-emerg px-6 text-mhl-emerg-ink">
      <form onSubmit={submit} className="w-full max-w-xs text-center">
        <span className="mx-auto grid h-14 w-14 place-items-center rounded-full border border-mhl-emerg-ink/25 text-mhl-emerg-amber">
          <LockIcon size={24} />
        </span>
        <h1 className="mt-4 text-mhl-title font-bold text-mhl-emerg-ink">This card is PIN-protected</h1>
        <p className="mt-2 text-mhl-body text-mhl-emerg-muted">Enter the PIN printed with the card.</p>
        <input
          type="text"
          inputMode="numeric"
          autoComplete="one-time-code"
          maxLength={8}
          value={value}
          onChange={(e) => {
            setValue(e.target.value);
            setError(null);
          }}
          aria-label="Card PIN"
          autoFocus
          className="mhl-no-ring mt-4 w-full rounded-mhl-sm border border-mhl-emerg-ink/30 bg-mhl-emerg-ink/10 px-4 py-3 text-center text-mhl-lead font-bold tracking-[0.35em] text-mhl-emerg-ink outline-none focus:border-mhl-emerg-amber"
        />
        {error && <p role="alert" className="mt-2 text-mhl-fine text-mhl-danger">{error}</p>}
        <button
          type="submit"
          disabled={busy}
          className="mt-4 flex w-full min-h-11 items-center justify-center rounded-full bg-mhl-emerg-ink px-6 text-mhl-body font-bold text-mhl-emerg disabled:opacity-50"
        >
          {busy ? "Verifying..." : "Open card"}
        </button>
      </form>
    </main>
  );
}

/**
 * The page the card's QR code and link open.
 *
 * Deliberately the same HealthSummary component the signed-in /app/summary page
 * uses, so both readers see identical sections, order and design. The owner's
 * section switches decide which blocks exist; there are no links into the app.
 */
function SummaryPage({ code, card }: { code: string; card: StaticEmergencyCard }) {
  const { shows } = card;
  const summary = card.summary;

  useEffect(() => {
    document.title = card.name ? `Medical summary: ${card.name}` : "Medical summary";
  }, [card.name]);

  const readings: SummaryReading[] = (summary?.vitals ?? []).map((v) => ({
    latest: {
      vitalType: v.vitalType,
      label: v.label,
      value: v.value,
      value2: v.value2,
      unit: v.unit,
      measuredAt: v.measuredAt,
    },
    values: v.values ?? [],
  }));

  const data: MedicalSummaryData = {
    profile: {
      fullName: card.name,
      dateOfBirth: card.dateOfBirth,
      sex: card.sex,
      bloodType: shows.bloodType ? card.bloodType : null,
      genotype: shows.bloodType ? card.genotype : null,
      emergencyContacts: shows.contacts
        ? card.contacts.map((contact, index) => ({
            name: contact.name,
            relationship: contact.relationship,
            phone: contact.phone,
            priority: index,
          }))
        : [],
    },
    allergies: shows.allergies ? (summary?.allergies ?? []) : [],
    conditions: shows.conditions
      ? (summary?.conditions ?? []).map((condition) => ({
          name: condition.name,
          status: condition.status,
          severity: condition.severity,
          onsetDate: condition.since,
          resolvedDate: null,
          notes: null,
        }))
      : [],
    medications: shows.medications ? (summary?.medications ?? []) : [],
    readings,
    appointments: summary?.appointments ?? [],
    labFindings: summary?.labFindings ?? [],
    pregnant: summary?.pregnant ?? false,
    focusOrder: (summary?.careFocus ?? []).filter((f) => f.kind === "condition").map((f) => f.label),
    medicineFlags: summary?.medicineFlags ?? [],
  };

  const meta = [
    card.sex ? (SEX_LABELS[card.sex as keyof typeof SEX_LABELS] ?? card.sex) : null,
    card.dateOfBirth ? `born ${formatDate(card.dateOfBirth)}` : null,
    shows.bloodType && card.bloodType ? `blood ${card.bloodType}` : null,
    shows.bloodType && card.genotype ? `genotype ${card.genotype}` : null,
  ]
    .filter(Boolean)
    .join(" · ");

  return (
    <main className="min-h-dvh bg-mhl-bg px-4 py-6 text-mhl-ink print:bg-white print:p-0">
      <div className="mx-auto max-w-5xl">
        <HealthSummary
          data={data}
          title="Medical summary"
          subtitle={`${card.name}${meta ? ` · ${meta}` : ""}. The facts a clinician asks for first.`}
          showLinks={false}
          sections={{
            allergies: shows.allergies,
            conditions: shows.conditions,
            medications: shows.medications,
            contacts: shows.contacts,
            readings: true,
            appointments: true,
          }}
          action={
            <button
              type="button"
              onClick={() => window.print()}
              className="print-hide inline-flex min-h-10 items-center justify-center rounded-full border border-mhl-rule bg-mhl-surface px-4 text-mhl-fine font-semibold text-mhl-ink hover:bg-mhl-sunk"
            >
              Print summary
            </button>
          }
          banner={
            <div className="rounded-mhl-sm border border-mhl-accent/25 bg-mhl-accent-lo px-4 py-3 text-mhl-fine text-mhl-ink">
              <p className="font-semibold">Emergency access</p>
              <p className="mt-0.5 text-mhl-muted">
                This is the same medical summary {card.name.split(" ")[0] || "the owner"} sees in their
                record, with the same flags. Only the sections they chose to share are shown.
              </p>
              {(summary?.careFocus?.length ?? 0) > 0 && (
                <div className="mt-2 border-t border-mhl-accent/20 pt-2">
                  <p className="font-semibold text-mhl-ink">Read first: their care focus</p>
                  <ol className="mt-1 space-y-0.5">
                    {summary!.careFocus!.map((f) => (
                      <li key={`${f.kind}:${f.label}`} className="text-mhl-ink">
                        <b>
                          {f.rank}. {f.label}
                        </b>{" "}
                        <span className="text-mhl-muted">{f.reason}</span>
                      </li>
                    ))}
                  </ol>
                  <p className="mt-1 text-mhl-muted">The conditions below are listed in this order.</p>
                </div>
              )}
              {shows.note && card.note && (
                <p className="mt-2 border-t border-mhl-accent/20 pt-2 text-mhl-ink">
                  <span className="font-semibold">Note from {card.name.split(" ")[0] || "the owner"}: </span>
                  {card.note}
                </p>
              )}
            </div>
          }
        />

        <footer className="mt-6 border-t border-mhl-rule pt-4 text-[0.75rem] leading-relaxed text-mhl-faint">
          <p>Opened {formatDateTime(new Date())} · Emergency code ····{tokenSuffix(code)}</p>
          <p className="mt-1">
            Shared by the person this summary belongs to. Emergency codes can be revoked at any time.
          </p>
        </footer>
      </div>
    </main>
  );
}

export default function EmergencyView() {
  const { code = "" } = useParams();
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);
  const [pinRequired, setPinRequired] = useState(false);
  const [card, setCard] = useState<StaticEmergencyCard | null>(null);

  useEffect(() => {
    if (!code) {
      setLoading(false);
      setError("No code provided.");
      return;
    }
    fetchPublicCard(code)
      .then((result) => {
        if (isPinRequired(result)) {
          setPinRequired(true);
        } else {
          setCard(result);
        }
      })
      .catch((err) => setError(apiErrorMessage(err)))
      .finally(() => setLoading(false));
  }, [code]);

  if (loading) {
    return (
      <main className="grid min-h-dvh place-items-center bg-mhl-emerg">
        <Spinner size={28} />
      </main>
    );
  }

  if (error) return <InvalidCode message={error} />;
  if (pinRequired && !card) {
    return (
      <PinGate
        code={code}
        onUnlock={(unlocked) => {
          setCard(unlocked);
          setPinRequired(false);
        }}
      />
    );
  }
  if (!card) return <InvalidCode />;
  return <SummaryPage code={code} card={card} />;
}
