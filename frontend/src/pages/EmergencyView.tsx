/**
 * The public emergency view — what a responder gets when they scan the code on the
 * card (Phase 3.2, "the doctor's first sixty seconds").
 *
 * It sits outside the signed-in app on purpose: no shell, no navigation, no account,
 * and nothing else reachable — the URL is a door into exactly one page and no
 * further. The token comes from the URL and is checked by lib/emergency.ts, the
 * stand-in for the backend's unauthenticated endpoint; the summary it hands back is
 * already filtered to severe allergies, current medicines and ongoing conditions, in
 * the order a clinician reads them.
 *
 * Everything here is near-black on near-white in the app's emergency register, built
 * to be read at arm's length in bad light and to print as it reads.
 */
import { useEffect, useMemo, useState, type FormEvent } from "react";
import { useParams } from "react-router-dom";
import {
  emergencyPinMatches,
  resolveEmergencyToken,
  tokenSuffix,
  type EmergencySummary,
} from "@/lib/emergency";
import { formatDate, formatDateTime, formatRelative } from "@/lib/format";
import { ALLERGY_SEVERITY_LABELS } from "@/types/health";
import { AllergyIcon, LockIcon, PhoneIcon, ShieldIcon } from "@/components/icons";

/** A phone dials digits; the record stores a display-friendly number. */
function telHref(phone: string): string {
  return `tel:${phone.replace(/[^\d+]/g, "")}`;
}

/** Small caps section heading — an emergency label, so caps are functional here. */
function SectionLabel({ children }: { children: string }) {
  return (
    <h2 className="text-mhl-fine font-bold tracking-[0.1em] text-mhl-emerg-faint">{children}</h2>
  );
}

function InvalidCode() {
  useEffect(() => {
    document.title = "Emergency view — code not valid";
  }, []);
  return (
    <main className="mhl-emerg-page grid min-h-dvh place-items-center bg-mhl-emerg px-6 text-mhl-emerg-ink">
      <div className="max-w-sm text-center">
        <span className="mx-auto grid h-14 w-14 place-items-center rounded-full border border-mhl-emerg-ink/25 text-mhl-emerg-amber">
          <ShieldIcon size={26} />
        </span>
        <h1 className="mt-4 text-mhl-title font-bold text-mhl-emerg-ink">
          This emergency code isn't valid
        </h1>
        <p className="mt-2 text-mhl-body text-mhl-emerg-muted">
          It may have been regenerated by the owner, or the link may be incomplete.
        </p>
        <p className="mt-4 text-mhl-fine text-mhl-emerg-faint">
          If this is your card: open myHealthLog, go to Emergency access, and print the
          card that carries your current code.
        </p>
      </div>
    </main>
  );
}

/** The owner's chosen gate. It isn't a login — the card's own PIN, the one printed
    with the code, checked before anything is revealed. */
function PinGate({ code, onUnlock }: { code: string; onUnlock: () => void }) {
  const [value, setValue] = useState("");
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    document.title = "Emergency view — enter PIN";
  }, []);

  function submit(event: FormEvent) {
    event.preventDefault();
    if (emergencyPinMatches(code, value)) {
      onUnlock();
      return;
    }
    setError("That PIN doesn't match this card.");
    setValue("");
  }

  return (
    <main className="mhl-emerg-page grid min-h-dvh place-items-center bg-mhl-emerg px-6 text-mhl-emerg-ink">
      <form onSubmit={submit} className="w-full max-w-xs text-center">
        <span className="mx-auto grid h-14 w-14 place-items-center rounded-full border border-mhl-emerg-ink/25 text-mhl-emerg-amber">
          <LockIcon size={24} />
        </span>
        <h1 className="mt-4 text-mhl-title font-bold text-mhl-emerg-ink">
          This card is PIN-protected
        </h1>
        <p className="mt-2 text-mhl-body text-mhl-emerg-muted">
          Enter the PIN printed with the card.
        </p>
        <input
          type="text"
          inputMode="numeric"
          autoComplete="one-time-code"
          maxLength={8}
          value={value}
          onChange={(e) => {
            setValue(e.target.value);
            setError(null);
          }}
          aria-label="Card PIN"
          autoFocus
          className="mt-4 w-full rounded-mhl-sm border border-mhl-emerg-ink/30 bg-mhl-emerg-ink/10 px-4 py-3 text-center text-mhl-lead font-bold tracking-[0.35em] text-mhl-emerg-ink outline-none focus:border-mhl-emerg-amber"
        />
        {error && (
          <p className="mt-2 text-mhl-fine text-mhl-emerg-alert" role="alert">
            {error}
          </p>
        )}
        <button
          type="submit"
          className="mt-4 inline-flex min-h-11 w-full items-center justify-center rounded-full bg-mhl-emerg-amber px-5 text-mhl-body font-semibold text-mhl-emerg transition-[filter] hover:brightness-95"
        >
          Open card
        </button>
      </form>
    </main>
  );
}

/** The card itself. Order is the clinician's reading order: who, then what will
    hurt them, then what they're on, then who to call. */
function SummaryPage({ code, summary }: { code: string; summary: EmergencySummary }) {
  useEffect(() => {
    document.title = `Emergency — ${summary.name}`;
  }, [summary.name]);

  const { shows } = summary;
  const primary = summary.contacts[0];
  const secondary = summary.contacts.slice(1);

  return (
    <main className="mhl-emerg-page min-h-dvh bg-mhl-emerg px-4 pb-10 pt-6 text-mhl-emerg-ink">
      <div className="mx-auto w-full max-w-md">
        <header className="flex items-center justify-between gap-3">
          <div className="flex items-center gap-2 text-mhl-emerg-amber">
            <ShieldIcon size={20} />
            <span className="text-mhl-fine font-bold tracking-[0.14em]">myHealthLog</span>
          </div>
          <span className="rounded-full border border-mhl-emerg-ink/25 px-2.5 py-1 text-[0.7rem] font-bold tracking-[0.08em] text-mhl-emerg-amber">
            EMERGENCY VIEW
          </span>
        </header>

        <section className="mt-6" aria-label="Who this card belongs to">
          <h1 className="text-[2rem] font-bold leading-tight text-mhl-emerg-ink">
            {summary.name || "—"}
          </h1>
          <p className="mt-1.5 text-mhl-body text-mhl-emerg-muted">
            {[
              summary.age != null ? `${summary.age} yrs` : null,
              summary.sex,
              summary.dateOfBirth ? `born ${formatDate(summary.dateOfBirth)}` : null,
            ]
              .filter(Boolean)
              .join(" · ")}
          </p>
          {shows.bloodType && (summary.bloodType || summary.genotype) && (
            <div className="mt-3 rounded-mhl border border-mhl-emerg-ink/20 bg-mhl-emerg-ink/10 px-4 py-3">
              <SectionLabel>Blood type &amp; genotype</SectionLabel>
              <p className="mt-0.5 text-[1.65rem] font-bold leading-none text-mhl-emerg-ink">
                {summary.bloodType ?? "—"}
                <span className="mx-2 text-mhl-emerg-muted">·</span>
                {summary.genotype ?? "—"}
              </p>
            </div>
          )}
        </section>

        {/* The profile the owner has open, where there is one. It sits beside the record
            it belongs to, never in place of it: this card always describes the whole
            person. Only shown when the owner already shares their conditions. */}
        {summary.context && (
          <p className="mt-3 rounded-mhl-sm border border-mhl-emerg-ink/20 px-4 py-2.5 text-mhl-fine text-mhl-emerg-ink">
            <span className="font-bold tracking-[0.08em] text-mhl-emerg-faint">
              RECORD CURRENTLY IN FOCUS:{" "}
            </span>
            {summary.context.label}
            {summary.context.detail ? ` · ${summary.context.detail}` : ""}
          </p>
        )}

        {/* The one block that changes treatment decisions — first, and loudest. */}
        {shows.allergies && (
          <section
            className="mt-4 rounded-mhl border-2 border-mhl-emerg-alert bg-mhl-emerg-alert/15 p-4"
            aria-label="Severe allergies"
          >
            <h2 className="flex items-center gap-2 text-mhl-fine font-bold tracking-[0.1em] text-mhl-emerg-alert">
              <AllergyIcon size={18} />
              SEVERE ALLERGIES — AVOID
            </h2>
            {summary.criticalAllergies.length === 0 ? (
              <p className="mt-2 text-mhl-body text-mhl-emerg-muted">
                No severe allergies recorded.
              </p>
            ) : (
              <ul className="mt-2.5 space-y-2.5">
                {summary.criticalAllergies.map((a) => (
                  <li key={a.substance}>
                    <p className="text-mhl-lead font-bold text-mhl-emerg-ink">
                      {a.substance}
                      <span className="ml-2 text-mhl-fine font-semibold text-mhl-emerg-alert">
                        {ALLERGY_SEVERITY_LABELS[a.severity]}
                      </span>
                    </p>
                    {a.reactions.length > 0 && (
                      <p className="text-mhl-fine text-mhl-emerg-muted">
                        {a.reactions.join(", ")}
                      </p>
                    )}
                  </li>
                ))}
              </ul>
            )}
          </section>
        )}

        {shows.medications && (
          <section
            className="mt-4 rounded-mhl border border-mhl-emerg-ink/20 p-4"
            aria-label="Current medicines"
          >
            <SectionLabel>CURRENT MEDICINES</SectionLabel>
            {summary.medications.length === 0 ? (
              <p className="mt-2 text-mhl-body text-mhl-emerg-muted">None recorded.</p>
            ) : (
              <ul className="mt-2 divide-y divide-mhl-emerg-ink/10">
                {summary.medications.map((m) => (
                  <li key={m.name} className="py-2 first:pt-0 last:pb-0">
                    <p className="text-mhl-body font-semibold text-mhl-emerg-ink">{m.name}</p>
                    <p className="text-mhl-fine text-mhl-emerg-muted">
                      {[m.dosage, m.frequency].filter(Boolean).join("  ·  ")}
                    </p>
                  </li>
                ))}
              </ul>
            )}
          </section>
        )}

        {shows.conditions && (
          <section
            className="mt-4 rounded-mhl border border-mhl-emerg-ink/20 p-4"
            aria-label="Ongoing conditions"
          >
            <SectionLabel>ONGOING CONDITIONS</SectionLabel>
            {summary.conditions.length === 0 ? (
              <p className="mt-2 text-mhl-body text-mhl-emerg-muted">None recorded.</p>
            ) : (
              <ul className="mt-2 divide-y divide-mhl-emerg-ink/10">
                {summary.conditions.map((c) => (
                  <li key={c.name} className="py-2 first:pt-0 last:pb-0">
                    <p className="text-mhl-body font-semibold text-mhl-emerg-ink">{c.name}</p>
                    {c.since && (
                      <p className="text-mhl-fine text-mhl-emerg-muted">
                        Since {formatDate(c.since)}
                      </p>
                    )}
                  </li>
                ))}
              </ul>
            )}
          </section>
        )}

        {shows.contacts && (
          <section className="mt-4" aria-label="Emergency contact">
            <SectionLabel>EMERGENCY CONTACT</SectionLabel>
            {primary ? (
              <a
                href={telHref(primary.phone)}
                className="mt-2 flex min-h-14 items-center gap-3 rounded-mhl-sm bg-mhl-emerg-amber px-4 py-3 text-mhl-emerg transition-[filter] hover:brightness-95"
              >
                <PhoneIcon size={22} className="flex-none" />
                <span className="min-w-0 flex-1">
                  <span className="block truncate text-mhl-body font-bold">
                    {primary.name}
                    {primary.relationship ? ` · ${primary.relationship}` : ""}
                  </span>
                  <span className="block text-mhl-fine text-mhl-emerg/80">{primary.phone}</span>
                </span>
                <span className="flex-none text-mhl-fine font-semibold">Tap to call</span>
              </a>
            ) : (
              <p className="mt-2 text-mhl-body text-mhl-emerg-muted">None recorded.</p>
            )}
            {secondary.length > 0 && (
              <ul className="mt-2 divide-y divide-mhl-emerg-ink/10">
                {secondary.map((c) => (
                  <li key={`${c.name}-${c.phone}`}>
                    <a
                      href={telHref(c.phone)}
                      className="flex items-center gap-2.5 py-2 text-mhl-body text-mhl-emerg-ink"
                    >
                      <PhoneIcon size={16} className="flex-none text-mhl-emerg-muted" />
                      <span className="min-w-0 flex-1 truncate">
                        {c.name}
                        {c.relationship ? ` · ${c.relationship}` : ""}
                      </span>
                      <span className="flex-none text-mhl-fine text-mhl-emerg-muted">
                        {c.phone}
                      </span>
                    </a>
                  </li>
                ))}
              </ul>
            )}
          </section>
        )}

        {shows.note && summary.note && (
          <p className="mt-4 rounded-mhl-sm bg-mhl-emerg-ink/10 px-4 py-3 text-mhl-body text-mhl-emerg-ink">
            {summary.note}
          </p>
        )}

        <footer className="mt-6 border-t border-mhl-emerg-ink/15 pt-4 text-[0.75rem] leading-relaxed text-mhl-emerg-faint">
          <p>
            Record last updated{" "}
            <span className="font-semibold text-mhl-emerg-muted">
              {summary.lastUpdated ? formatRelative(summary.lastUpdated) : "unknown"}
            </span>
          </p>
          <p className="mt-1">
            Opened {formatDateTime(new Date())} · Emergency code ····{tokenSuffix(code)}
          </p>
          <p className="mt-2 text-mhl-emerg-muted">
            Shared by the person this card belongs to — it contains only what they chose
            to show. For anything else, ask them or their contact.
          </p>
          <button
            type="button"
            onClick={() => window.print()}
            className="print-hide mt-3 inline-flex min-h-11 items-center justify-center rounded-full border border-mhl-emerg-ink/25 px-5 text-mhl-fine font-semibold text-mhl-emerg-ink hover:bg-mhl-emerg-ink/10"
          >
            Print this card
          </button>
        </footer>
      </div>
    </main>
  );
}

export default function EmergencyView() {
  const { code = "" } = useParams();
  const resolved = useMemo(() => resolveEmergencyToken(code), [code]);
  const [unlocked, setUnlocked] = useState(false);

  if (!resolved) return <InvalidCode />;
  if (resolved.pinRequired && !unlocked) {
    return <PinGate code={code} onUnlock={() => setUnlocked(true)} />;
  }
  return <SummaryPage code={code} summary={resolved.summary} />;
}
